class TestConvert:
    def test_formal_and_temporary_users_keep_their_data(self, repo, directory):
        formal = cloud_user(repo, 101, privilege=3, drive=("a@gmail.com", "share-a"))
        temp = cloud_user(repo, 201)
        legacy_playlist(repo, formal, "road trip", songs=3)
        legacy_playlist(repo, temp, "fav", songs=1)
        legacy_netbird(repo, formal, "group-a")
        external(repo, formal, PlatformType.Twitch, "tw-a")
        external(repo, temp, PlatformType.Minecraft, "mc-b")
        account = _account(username="alice", roles=("admin",))
        directory.accounts[101] = account

        report = run(repo, directory, dry_run=False)

        assert user_id_type(repo) == "uuid"
        assert playlists(repo, account.account_id) == ["road trip"]
        assert repo.get_netbird_binding(account.account_id).group_id == "group-a"
        assert repo.session.get(DriveShare, account.account_id).share_id == "share-a"
        ident = repo.get_discord_identity(101)
        assert (ident.user_id, ident.is_formal, ident.username, ident.roles) == (account.account_id, True, "alice", ["admin"])

        temp_ident = repo.get_discord_identity(201)
        assert temp_ident.is_formal is False
        assert playlists(repo, temp_ident.user_id) == ["fav"]
        linked = {(r.user_id, r.platform, r.external_id) for r in repo.session.exec(select(LinkedAccount)).all()}
        assert linked == {(account.account_id, PlatformType.Twitch, "tw-a"), (temp_ident.user_id, PlatformType.Minecraft, "mc-b")}

        assert report.before == report.after == {"playlists": 2, "songs": 4, "sources": 0, "netbird": 1, "linked": 2, "drive": 1}
        assert [u.cloud_user_id for u in report.admins] == [formal]

    def test_only_primary_discord_gets_identity(self, repo, directory):
        cid = cloud_user(repo, 101, 102)
        legacy_playlist(repo, cid, "fav")

        run(repo, directory, dry_run=False)

        assert repo.get_discord_identity(101) is not None
        assert repo.get_discord_identity(102) is None
        assert repo.session.exec(select(LinkedAccount)).all() == []

    def test_schema_matches_model_after_conversion(self, repo, directory):
        cid = cloud_user(repo, 101)
        legacy_playlist(repo, cid, "fav")
        legacy_netbird(repo, cid, "group-a")
        run(repo, directory, dry_run=False)
        user_id = repo.get_discord_identity(101).user_id

        with pytest.raises(Exception):
            repo.create_music_playlist(user_id, "fav")
        repo.session.rollback()
        repo.session.add(NetBirdBinding(user_id=user_id, group_id="dup"))
        with pytest.raises(Exception):
            repo.session.flush()
        repo.session.rollback()
        constraints = repo.session.execute(
            text("SELECT conname FROM pg_constraint WHERE conrelid IN ('users.music_playlist'::regclass, 'users.netbird_binding'::regclass) AND contype = 'f'")
        ).all()
        assert constraints == []


class TestMerge:
    def test_two_cloud_users_of_same_citizen_are_merged(self, repo, directory):
        first = cloud_user(repo, 101)
        second = cloud_user(repo, 201)
        legacy_playlist(repo, first, "fav", songs=1)
        legacy_playlist(repo, second, "fav", songs=2)
        legacy_netbird(repo, first, "group-first")
        legacy_netbird(repo, second, "group-second")
        account = _account()
        directory.accounts[101] = account
        directory.accounts[201] = account

        report = run(repo, directory, dry_run=False)

        assert playlists(repo, account.account_id) == ["fav", "fav (2)"]
        assert repo.get_netbird_binding(account.account_id).group_id == "group-first"
        assert repo.get_discord_identity(201).user_id == account.account_id
        assert [u.merged for u in report.users] == [False, True]
        assert report.after["songs"] == 3
        assert report.after["netbird"] == 1


class TestSafety:
    def test_dry_run_leaves_database_unchanged(self, repo, directory):
        cid = cloud_user(repo, 101)
        legacy_playlist(repo, cid, "fav")
        directory.accounts[101] = _account(username="alice")

        report = run(repo, directory, dry_run=True)

        assert report.dry_run
        assert report.users[0].is_formal
        assert report.after["playlists"] == 1
        assert user_id_type(repo) == "integer"
        assert repo.session.exec(select(DiscordIdentity)).all() == []
        assert "dry-run" in format_report(report)

    def test_auth_unavailable_aborts_without_writing(self, repo):
        cloud_user(repo, 101)
        cloud_user(repo, 201)
        directory = FailOnCall(fail_at=2)

        with pytest.raises(MigrationAborted):
            run(repo, directory, dry_run=False)

        assert user_id_type(repo) == "integer"
        assert repo.session.exec(select(DiscordIdentity)).all() == []

    def test_second_run_is_refused(self, repo, directory):
        cloud_user(repo, 101)
        run(repo, directory, dry_run=False)

        with pytest.raises(MigrationAborted, match="已經轉換過"):
            run(repo, directory, dry_run=False)

    def test_user_without_discord_is_skipped_when_it_has_no_data(self, repo, directory):
        orphan = cloud_user(repo)
        cloud_user(repo, 101)

        report = run(repo, directory, dry_run=False)

        assert [u.cloud_user_id for u in report.skipped] == [orphan]

    def test_user_without_discord_but_with_data_aborts(self, repo, directory):
        orphan = cloud_user(repo)
        legacy_playlist(repo, orphan, "fav")

        with pytest.raises(MigrationAborted, match="沒有 Discord"):
            run(repo, directory, dry_run=False)
        assert user_id_type(repo) == "integer"

    def test_partial_drive_aborts(self, repo, directory):
        repo.session.execute(text("INSERT INTO users.cloud_user (drive_gmail) VALUES ('a@gmail.com')"))
        repo.session.commit()

        with pytest.raises(MigrationAborted, match="雲端資料夾"):
            run(repo, directory, dry_run=False)

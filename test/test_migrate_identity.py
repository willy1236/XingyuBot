# 正式機 users schema 的舊表，取自 pg_dump
LEGACY_DDL = """
CREATE TABLE users.cloud_user (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    drive_gmail character varying,
    drive_share_id character varying,
    name character varying,
    created_at timestamp(0) with time zone DEFAULT now(),
    privilege_level smallint
);
CREATE TABLE users.external_account (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users.cloud_user(id),
    platform smallint,
    external_id character varying,
    display_name character varying,
    platform_data json,
    CONSTRAINT unique_platform_account UNIQUE (platform, external_id)
);
CREATE TABLE users.link_code (
    user_id integer PRIMARY KEY REFERENCES users.cloud_user(id),
    code character varying NOT NULL,
    expires_at timestamp(0) with time zone
);
CREATE TABLE users.music_playlist (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users.cloud_user(id),
    name character varying NOT NULL,
    created_at timestamp(0) with time zone DEFAULT now(),
    CONSTRAINT unique_user_playlist_name UNIQUE (user_id, name)
);
CREATE INDEX ix_users_music_playlist_user_id ON users.music_playlist (user_id);
CREATE TABLE users.music_playlist_source (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    playlist_id integer NOT NULL REFERENCES users.music_playlist(id) ON DELETE CASCADE,
    url character varying NOT NULL,
    title character varying,
    synced_at timestamp(0) with time zone DEFAULT now(),
    CONSTRAINT unique_playlist_source_url UNIQUE (playlist_id, url)
);
CREATE TABLE users.music_playlist_song (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    playlist_id integer NOT NULL REFERENCES users.music_playlist(id) ON DELETE CASCADE,
    source_id integer REFERENCES users.music_playlist_source(id) ON DELETE SET NULL,
    "position" integer NOT NULL,
    url character varying NOT NULL,
    title character varying NOT NULL,
    duration integer
);
CREATE TABLE users.netbird_binding (
    user_id integer PRIMARY KEY REFERENCES users.cloud_user(id),
    group_id character varying,
    group_name character varying,
    last_setup_key_id character varying,
    created_at timestamp(0) with time zone,
    updated_at timestamp(0) with time zone
);
"""


@pytest.fixture
def repo():
    """舊 schema 的暫時資料庫：先建舊表，再照 bot 啟動時一樣 create_all 補新表"""
    name = f"migtest_{uuid4().hex[:12]}"
    admin = sqldb.engine.execution_options(isolation_level="AUTOCOMMIT")
    with admin.connect() as conn:
        conn.execute(text(f'CREATE DATABASE "{name}"'))
    engine = create_engine(sqldb.engine.url.set(database=name))
    session = Session(engine)
    try:
        with engine.begin() as conn:
            for schema in {t.schema for t in SQLModel.metadata.tables.values() if t.schema}:
                conn.execute(text(f'CREATE SCHEMA "{schema}"'))
            conn.execute(text(LEGACY_DDL))
        SQLModel.metadata.create_all(engine)
        yield SQLRepository(engine, session)
    finally:
        session.close()
        engine.dispose()
        with admin.connect() as conn:
            conn.execute(text(f'DROP DATABASE "{name}" WITH (FORCE)'))


def cloud_user(repo: SQLRepository, *discord_ids: int, privilege: int = 0, drive: tuple[str, str] | None = None) -> int:
    gmail, share_id = drive or (None, None)
    cid = repo.session.execute(
        text("INSERT INTO users.cloud_user (privilege_level, drive_gmail, drive_share_id) VALUES (:p, :g, :s) RETURNING id"),
        {"p": privilege, "g": gmail, "s": share_id},
    ).scalar()
    for discord_id in discord_ids:
        external(repo, cid, PlatformType.Discord, str(discord_id))
    repo.session.commit()
    return cid


def external(repo: SQLRepository, cid: int, platform: PlatformType, external_id: str):
    repo.session.execute(
        text("INSERT INTO users.external_account (user_id, platform, external_id, display_name, platform_data) VALUES (:u, :p, :e, :e, '{}')"),
        {"u": cid, "p": platform, "e": external_id},
    )
    repo.session.commit()


def legacy_playlist(repo: SQLRepository, cid: int, name: str, songs: int = 0) -> int:
    pid = repo.session.execute(text("INSERT INTO users.music_playlist (user_id, name) VALUES (:u, :n) RETURNING id"), {"u": cid, "n": name}).scalar()
    for i in range(songs):
        repo.session.execute(
            text("INSERT INTO users.music_playlist_song (playlist_id, position, url, title) VALUES (:p, :i, :u, :t)"),
            {"p": pid, "i": i, "u": f"https://example.com/{i}", "t": f"song {i}"},
        )
    repo.session.commit()
    return pid


def legacy_netbird(repo: SQLRepository, cid: int, group_id: str):
    repo.session.execute(text("INSERT INTO users.netbird_binding (user_id, group_id) VALUES (:u, :g)"), {"u": cid, "g": group_id})
    repo.session.commit()


def run(repo: SQLRepository, directory, *, dry_run: bool):
    return asyncio.run(migrate(repo, directory, dry_run=dry_run))


def user_id_type(repo: SQLRepository) -> str:
    return repo.session.execute(
        text("SELECT data_type FROM information_schema.columns WHERE table_schema = 'users' AND table_name = 'music_playlist' AND column_name = 'user_id'")
    ).scalar()


def playlists(repo: SQLRepository, user_id: UUID) -> list[str]:
    return sorted(p.name for p in repo.get_music_playlists(user_id))


class FailOnCall(FakeDirectory):
    def __init__(self, fail_at: int):
        super().__init__()
        self.fail_at = fail_at

    async def find_by_discord(self, discord_id: int):
        if self.calls + 1 == self.fail_at:
            self.unavailable = True
        return await super().find_by_discord(discord_id)


